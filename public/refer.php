<script>
(function () {
    document.querySelectorAll('.section-fade').forEach(function (el) {
        new IntersectionObserver(function (entries) {
            entries.forEach(function (e) { if (e.isIntersecting) e.target.classList.add('visible'); });
        }, { threshold: 0.08 }).observe(el);
    });

    var form    = document.getElementById('referForm');
    var btn     = document.getElementById('referBtn');
    var alert   = document.getElementById('referAlert');
    var success = document.getElementById('referSuccess');

    form.addEventListener('submit', function (e) {
        e.preventDefault();
        alert.classList.add('hidden');
        btn.disabled    = true;
        btn.textContent = 'Submitting…';

        var apps = [];
        document.querySelectorAll('input[name="app"]:checked').forEach(function (cb) { apps.push(cb.value); });

        fetch('api/refer/submit.php', {
            method:  'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
                your_name:    document.getElementById('rYourName').value,
                your_email:   document.getElementById('rYourEmail').value,
                biz_name:     document.getElementById('rBizName').value,
                industry:     document.getElementById('rIndustry').value,
                contact_name: document.getElementById('rContactName').value,
                contact_info: document.getElementById('rContactInfo').value,
                apps:         apps,
                notes:        document.getElementById('rNotes').value,
            }),
        })
        .then(function (r) { return r.json(); })
        .then(function (data) {
            if (data.success) {
                form.classList.add('hidden');
                success.classList.remove('hidden');
            } else {
                alert.textContent = data.message || 'Something went wrong. Please try again.';
                alert.classList.remove('hidden');
                btn.disabled    = false;
                btn.textContent = 'Submit Referral';
            }
        })
        .catch(function () {
            alert.textContent = 'Network error. Please try again.';
            alert.classList.remove('hidden');
            btn.disabled    = false;
            btn.textContent = 'Submit Referral';
        });
    });
}());
</script>

